const isOrderedRewriteRange = (range: AgentRewriteConflictRange): boolean => {
  const startIndex = range.targetNodeIds.indexOf(range.startNodeId);
  const endIndex = range.targetNodeIds.indexOf(range.endNodeId);
  if (startIndex < 0 || endIndex < 0 || startIndex > endIndex) return false;
  return startIndex !== endIndex || range.startOffset <= range.endOffset;
};

/**
 * Compare two durable rewrite ranges as half-open character intervals.
 *
 * A block-id projection alone is intentionally insufficient: two selections
 * in different portions of the same paragraph are independent. `undefined`
 * means that one range cannot be trusted (for example, an older awareness
 * payload); callers can then apply their compatibility fallback.
 */
export const hasOverlappingRewriteRanges = (
  left: AgentRewriteConflictRange,
  right: AgentRewriteConflictRange,
): boolean | undefined => {
  if (
    !isAgentRewriteRange(left) ||
    !isAgentRewriteRange(right) ||
    left.targetNodeIds.length === 0 ||
    right.targetNodeIds.length === 0 ||
    !isOrderedRewriteRange(left) ||
    !isOrderedRewriteRange(right)
  ) {
    return undefined;
  }

  const rightIds = new Set(right.targetNodeIds);
  for (const nodeId of left.targetNodeIds) {
    if (!rightIds.has(nodeId)) continue;

    // Non-endpoint blocks are fully covered by a cross-block range. Infinity
    // is a sentinel here; the strict comparison below makes touching
    // half-open boundaries non-overlapping without requiring block lengths.
    const leftStart = nodeId === left.startNodeId ? left.startOffset : 0;
    const leftEnd = nodeId === left.endNodeId ? left.endOffset : Number.POSITIVE_INFINITY;
    const rightStart = nodeId === right.startNodeId ? right.startOffset : 0;
    const rightEnd = nodeId === right.endNodeId ? right.endOffset : Number.POSITIVE_INFINITY;

    if (Math.max(leftStart, rightStart) < Math.min(leftEnd, rightEnd)) return true;
  }

  return false;
};

const sameStringArray = (left: ReadonlyArray<string>, right: ReadonlyArray<string>): boolean =>
  left.length === right.length && left.every((value, index) => value === right[index]);

/**
 * A restricted headless editor facade for a collaborative Agent worker.
 *
 * The underlying editor kernel, Lexical editor, Yjs binding, and Y.Doc remain
 * private. Agent code can resolve a durable selection, set awareness, dispatch
 * an allowlisted command, but cannot call setDocument or mutate Yjs directly
 * through this facade. Snapshot export belongs to the internal room
 * persistence adapter, not to an Agent worker's public API.
 */
export class CollaborativeAgentEditor {
  /**
   * Construct an isolated, unconnected Agent facade.
   *
   * The constructor remains private so callers receive neither the Y.Doc nor
   * the provider/kernel. This pre-connect entry exists for workers that need
   * to publish `connecting` awareness before authentication and initial sync
   * complete; call the instance `connect()` to start the network lifecycle.
   */
  static create(options: CollaborativeAgentEditorConnectOptions): CollaborativeAgentEditor {
    validateConnectOptions(options);
    const yjsDoc = new Doc();
    try {
      const provider = new NodeWebSocketYjsProvider(options.roomId, yjsDoc, {
        ...options.providerOptions,
        documentId: options.documentId,
        requestId: options.requestId,
        ticket: options.ticket,
      });
      return new CollaborativeAgentEditor({
        ...options,
        ownsDoc: true,
        provider,
        yjsDoc,
      });
    } catch (error) {
      yjsDoc.destroy();
      throw error;
    }
  }

  static async connect(
    options: CollaborativeAgentEditorConnectOptions,
  ): Promise<CollaborativeAgentEditor> {
    const session = CollaborativeAgentEditor.create(options);

    try {
      await session.connect();
      return session;
    } catch (error) {
      await session.disconnect();
      throw error;
    }
  }

  private readonly documentId: string;
  private readonly kernel: IEditor;
  private readonly ownsDoc: boolean;
  private readonly provider: CollaborativeAgentProvider;
  private readonly commandGateway: CollaborativeAgentCommandGateway;
  private readonly resultChannel: RewriteCommandResultChannel;
  private readonly requestId: string;
  private readonly roomId: string;
  private readonly yjsDoc: Doc;
  private transportUnavailable = false;
  private connected = false;
  private disconnected = false;
  private synced = false;
  private providerSyncPromise: Promise<void> | null = null;
  /**
   * Streaming sessions are deliberately local orchestration state. The
   * document itself is the durable checkpoint: every chunk is already
   * mirrored to Yjs before the method resolves. A reconnect can therefore
   * either continue with an existing in-memory session or safely stop it
   * without ever restoring the replaced text.
   */
  private readonly rewriteSessions = new Map<string, CollaborativeRewriteStreamState>();
  private readonly recoveredRewriteSessions = new Map<string, CollaborativeRewriteStreamResult>();
  private readonly syncWaiters = new Set<{
    reject: (error: Error) => void;
    resolve: () => void;
  }>();

  private constructor(options: CollaborativeAgentEditorInternalOptions) {
    if (
      typeof options.provider.connect !== 'function' ||
      typeof options.provider.disconnect !== 'function' ||
      !options.provider.awareness ||
      typeof options.provider.awareness.getStates !== 'function'
    ) {
      throw new Error('CollaborativeAgentEditor provider is invalid.');
    }

    this.documentId = options.documentId;
    this.requestId = options.requestId;
    this.roomId = options.roomId;
    this.ownsDoc = options.ownsDoc;
    this.yjsDoc = options.yjsDoc;
    this.provider = options.provider;
    this.provider.on('status', this.providerStatusListener);
    this.provider.on('sync', this.providerSyncListener);

    const yjsPlugin: IPlugin = [
      YjsPlugin,
      {
        id: this.roomId,
        providerFactory: () => this.provider,
        shouldBootstrap: false,
        yjsDoc: this.yjsDoc,
      },
    ];
    this.kernel = Editor.createEditor();
    this.kernel.registerPlugins([...DEFAULT_HEADLESS_EDITOR_PLUGINS, yjsPlugin]);
    const lexicalEditor = this.kernel.initHeadlessEditor();
    if (!lexicalEditor) throw new Error('CollaborativeAgentEditor failed to initialize editor.');
    internalStates.set(this, { kernel: this.kernel });
    this.resultChannel =
      this.kernel.requireService(IRewriteCommandResultService) ??
      (() => {
        throw new Error('Rewrite command result channel is not registered.');
      })();
    this.commandGateway = createCollaborativeAgentCommandGateway(lexicalEditor, this.resultChannel);
  }

  async connect(): Promise<this> {
    if (this.disconnected) throw new Error('CollaborativeAgentEditor is disconnected.');
    if (this.connected) {
      if (!this.synced) await this.waitForSync();
      return this;
    }

    this.connected = true;
    this.transportUnavailable = false;
    try {
      const syncPromise = this.waitForSync();
      await this.provider.connect();
      await syncPromise;
      await moment();
      if (this.transportUnavailable) {
        throw new Error('CollaborativeAgentEditor provider disconnected during sync.');
      }
      this.synced = true;
    } catch (error) {
      this.connected = false;
      this.transportUnavailable = true;
      this.syncWaiters.forEach(({ reject }) =>
        reject(error instanceof Error ? error : new Error('Yjs provider connection failed.')),
      );
      this.syncWaiters.clear();
      this.providerSyncPromise = null;
      throw error;
    }
    return this;
  }

  async waitForSync(): Promise<void> {
    if (this.synced) return;
    if (this.disconnected) throw new Error('CollaborativeAgentEditor is disconnected.');

    const providerSync = this.getProviderSyncPromise();
    await new Promise<void>((resolve, reject) => {
      const waiter = { reject, resolve };
      this.syncWaiters.add(waiter);
      providerSync.then(
        () => {
          this.syncWaiters.delete(waiter);
          if (this.disconnected) {
            reject(new Error('CollaborativeAgentEditor is disconnected.'));
            return;
          }
          resolve();
        },
        (error: unknown) => {
          this.syncWaiters.delete(waiter);
          reject(error instanceof Error ? error : new Error('Yjs provider sync failed.'));
        },
      );
    });
  }

  getStateVector(): string {
    if (typeof this.provider.getStateVector === 'function') {
      return this.provider.getStateVector();
    }

    const service = this.getYjsServiceState();
    if (!service?.doc) throw new Error('Yjs binding is not initialized.');

    return encodeYjsBase64(encodeStateVector(service.doc));
  }

  private getStateVectorSafely(): string | null {
    try {
      return this.getStateVector();
    } catch {
      return null;
    }
  }

  setAgentAwareness(input: AgentAwarenessInput | AgentAwarenessState): void {
    if (this.disconnected) throw new Error('CollaborativeAgentEditor is disconnected.');
    const awarenessData = isFullAgentAwarenessState(input)
      ? input.awarenessData
      : {
          documentId: input.documentId,
          requestId: input.requestId,
        };
    if (
      awarenessData.documentId !== this.documentId ||
      awarenessData.requestId !== this.requestId ||
      (isFullAgentAwarenessState(input) && input.awarenessData.role !== 'agent')
    ) {
      throw new Error('Agent awareness identity does not match this request.');
    }

    if (typeof this.provider.setAgentAwareness === 'function') {
      this.provider.setAgentAwareness(input);
      return;
    }

    this.provider.awareness.setLocalState(
      isFullAgentAwarenessState(input)
        ? input
        : {
            anchorPos: input.anchorPos ?? null,
            awarenessData: {
              ...(input.caret === undefined ? {} : { caret: input.caret }),
              documentId: input.documentId,
              ...(input.generationId ? { generationId: input.generationId } : {}),
              requestId: input.requestId,
              role: 'agent',
              ...(input.selectionRange ? { selectionRange: { ...input.selectionRange } } : {}),
              ...(input.sessionId ? { sessionId: input.sessionId } : {}),
              status: input.status,
              ...(input.targetNodeIds ? { targetNodeIds: [...input.targetNodeIds] } : {}),
            },
            ...(input.caret === undefined ? {} : { caret: input.caret }),
            color: input.color ?? '#7c3aed',
            focusPos: input.focusPos ?? input.anchorPos ?? null,
            focusing: input.focusing ?? (input.status !== 'done' && input.status !== 'error'),
            name: input.name ?? 'AI Agent',
          },
    );
  }

  setAgentStatus(status: AgentAwarenessStatus): void {
    if (status === 'done' || status === 'error') {
      this.clearAwareness();
      return;
    }
    const state = this.provider.awareness.getLocalState();
    if (!state || typeof state.awarenessData !== 'object' || state.awarenessData === null) return;

    this.provider.awareness.setLocalState({
      ...state,
      awarenessData: {
        ...state.awarenessData,
        status,
      },
      focusing: true,
    });
  }

  /** Clear the Agent cursor/state without exposing the underlying provider. */
  clearAwareness(): void {
    if (this.disconnected) return;
    if (!this.provider.awareness.getLocalState()) return;
    if (typeof this.provider.clearAgentAwareness === 'function') {
      this.provider.clearAgentAwareness();
      return;
    }
    this.provider.awareness.setLocalState(null);
  }

  resolveSelection(selection: CollaborativeRewriteSelection): ResolvedRewriteSelection | null {
    if (!selection || typeof selection !== 'object' || this.disconnected) return null;
    if (selection.kind === 'relative' && selection.roomId !== this.roomId) {
      return null;
    }

    const service = this.getYjsServiceState();
    const lexicalEditor = service?.binding.editor;
    if (!service || !lexicalEditor) return null;

    if (selection.kind === 'relative') {
      return this.resolveRelativeSelection(selection, service.binding, lexicalEditor);
    }

    return this.resolveBlockSelection(selection, lexicalEditor);
  }

  /**
   * Return which durable rewrite targets still exist in this synced editor.
   * This is intentionally read-only and safe to call before the first stream
   * chunk, when selection-relative resolution may already be unavailable.
   */
  inspectRewriteTargets(targetNodeIds: ReadonlyArray<string>): RewriteTargetInspection {
    const requested = Array.isArray(targetNodeIds) ? targetNodeIds : [];
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor || this.disconnected) {
      const normalized = [...new Set(requested.filter(isValidNodeId))];
      return { existingNodeIds: [], missingNodeIds: normalized };
    }

    let inspection: RewriteTargetInspection = {
      existingNodeIds: [],
      missingNodeIds: [...new Set(requested.filter(isValidNodeId))],
    };
    lexicalEditor.getEditorState().read(() => {
      inspection = inspectDurableTargetNodeIds(requested);
    });
    return inspection;
  }

  setSelection(selection: BaseSelection): boolean {
    if (this.disconnected) return false;
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) return false;
    if (!$isRangeSelection(selection)) return false;

    let didSet = false;
    lexicalEditor.update(
      () => {
        const anchorNode = $getNodeByKey(selection.anchor.key);
        const focusNode = $getNodeByKey(selection.focus.key);
        if (!anchorNode || !focusNode) return;

        const nextSelection = $createRangeSelection();
        nextSelection.anchor.set(
          selection.anchor.key,
          selection.anchor.offset,
          selection.anchor.type,
        );
        nextSelection.focus.set(selection.focus.key, selection.focus.offset, selection.focus.type);
        $setSelection(nextSelection);
        didSet = true;
      },
      { discrete: true },
    );
    return didSet;
  }

  dispatchCommand(
    command: CollaborativeAgentCommand,
    payload: unknown,
  ): Promise<RewriteCommandResult> {
    if (this.disconnected || !this.synced || this.transportUnavailable) {
      return Promise.reject(
        new Error('CollaborativeAgentEditor must be synced before dispatching commands.'),
      );
    }

    if (!this.commandGateway.isAllowed(command as LexicalCommand<unknown>)) {
      return Promise.reject(new Error('Command is not allowed for collaborative Agent editing.'));
    }

    const payloadRequestId = getPayloadRequestId(payload);
    if (payloadRequestId !== this.requestId) {
      return Promise.reject(new Error('Command requestId does not match this Agent session.'));
    }

    let sessionPayload = attachSessionRequestId(payload, this.requestId);

    // Relative positions are the durable browser/Agent wire format, but the
    // Lexical command itself consumes only a short-lived block/offset range.
    // Resolve and normalize inside this synced facade so no runtime node key
    // or raw Yjs object is ever persisted or sent through the command result.
    if (
      command === LITEXML_REWRITE_RANGE_COMMAND &&
      sessionPayload &&
      typeof sessionPayload === 'object' &&
      !Array.isArray(sessionPayload)
    ) {
      const rewritePayload = sessionPayload as Record<string, unknown>;
      const selection = rewritePayload.selection;
      if (
        selection &&
        typeof selection === 'object' &&
        !Array.isArray(selection) &&
        (selection as { kind?: unknown }).kind === 'relative'
      ) {
        const resolved = this.resolveSelection(selection as CollaborativeRewriteSelection);
        if (
          resolved?.startNodeId &&
          resolved.endNodeId &&
          resolved.startOffset !== undefined &&
          resolved.endOffset !== undefined
        ) {
          const backward = resolved.isBackward === true;
          const start = {
            nodeId: resolved.startNodeId,
            offset: resolved.startOffset,
          };
          const end = {
            nodeId: resolved.endNodeId,
            offset: resolved.endOffset,
          };
          sessionPayload = {
            ...rewritePayload,
            selection: {
              anchor: backward ? end : start,
              focus: backward ? start : end,
              quotedText: resolved.quotedText,
              quotedTextHash: hashRewriteText(resolved.quotedText),
              targetNodeIds: resolved.targetNodeIds,
              type: 'range' as const,
            },
          };
          sessionPayload = attachSessionRequestId(sessionPayload, this.requestId);
        }
      }
    }

    return this.commandGateway.dispatch(command as LexicalCommand<unknown>, sessionPayload);
  }

  /**
   * Start an incremental direct rewrite.
   *
   * The selected text is removed exactly once. Subsequent chunks are inserted
   * as new formatted text leaves at a durable block/offset caret, so peers see
   * each update through the normal Lexical/Yjs bridge rather than receiving a
   * rebuilt document snapshot.
   */
  async startRewriteSession(
    input: CollaborativeRewriteStreamStartInput,
  ): Promise<CollaborativeRewriteStreamResult> {
    const sessionId = isValidStreamId(input?.sessionId) ? input.sessionId.trim() : '';
    const generationId = isValidStreamId(input?.generationId) ? input.generationId.trim() : '';
    const provenanceSessionId =
      input?.provenanceSessionId === undefined
        ? undefined
        : isValidStreamId(input.provenanceSessionId)
          ? input.provenanceSessionId.trim()
          : '';

    if (!sessionId || !generationId) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'sessionId-and-generationId-required',
      );
    }
    if (input.provenanceSessionId !== undefined && !provenanceSessionId) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'provenanceSessionId-invalid',
      );
    }
    if (
      input.turnIndex !== undefined &&
      (!Number.isSafeInteger(input.turnIndex) || input.turnIndex < 0)
    ) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'turnIndex-invalid',
      );
    }
    if (!isValidStreamId(input?.requestId)) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'requestId-required',
      );
    }
    if (input.requestId !== this.requestId) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'requestId does not match this Agent session.',
      );
    }
    if (!this.isReadyForStreaming()) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'stopped',
        'CollaborativeAgentEditor must be synced before starting a stream.',
      );
    }

    const previous = this.rewriteSessions.get(sessionId);
    if (previous) {
      if (
        previous.generationId !== generationId ||
        previous.originalTextHash !== input.expectedTextHash ||
        previous.provenanceSessionId !== provenanceSessionId ||
        previous.turnIndex !== input.turnIndex ||
        !Array.isArray(input.selection?.targetNodeIds) ||
        !sameStringArray(previous.selectionTargetNodeIds, input.selection.targetNodeIds)
      ) {
        return this.createStandaloneStreamResult(
          sessionId,
          generationId,
          'failed',
          'stream-session-id-reused',
        );
      }
      // A retry of start is a pure read. Returning the exact state also makes
      // reconnect/replay callers safe when the original response was lost.
      return this.copyStreamingResult(previous.lastResult);
    }

    if (!isValidStreamId(input.expectedTextHash)) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'expectedTextHash-required',
      );
    }
    if (!input.selection || !Array.isArray(input.selection.targetNodeIds)) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'targetNodeIds-required',
      );
    }
    if (
      input.selection.targetNodeIds.length === 0 ||
      !isValidTargetNodeIds(input.selection.targetNodeIds)
    ) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        'targetNodeIds-invalid',
      );
    }

    const resolved = this.resolveSelection(input.selection);
    if (!resolved) {
      const targetInspection = this.inspectRewriteTargets(input.selection.targetNodeIds);
      const error =
        targetInspection.missingNodeIds.length > 0 ? 'region_missing' : 'generation_conflict';
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        error,
        input.selection.targetNodeIds,
      );
    }
    let selectionHasInlineDecorator = false;
    const lexicalEditorForSelection = this.getLexicalEditor();
    lexicalEditorForSelection?.getEditorState().read(() => {
      selectionHasInlineDecorator = selectionContainsInlineDecorator(resolved.selection);
    });
    if (selectionHasInlineDecorator) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        'rewrite-selection-inline-decorator-unsupported',
        resolved.targetNodeIds,
      );
    }
    // A changed state vector is only diagnostic here. The durable target
    // projection, live quote hash, and offsets below are the authoritative
    // proof. This lets a user keep editing unrelated blocks while the Agent
    // is thinking, without weakening same-target conflict detection.
    if (hashRewriteText(resolved.quotedText) !== input.expectedTextHash) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        'rewrite-selection-hash-mismatch',
        resolved.targetNodeIds,
      );
    }
    if (
      !resolved.startNodeId ||
      resolved.startOffset === undefined ||
      !resolved.endNodeId ||
      resolved.endOffset === undefined ||
      !resolved.targetNodeIds ||
      !sameStringArray(resolved.targetNodeIds, input.selection.targetNodeIds)
    ) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        'rewrite-selection-target-mismatch',
        resolved.targetNodeIds,
      );
    }

    const selectionRange: AgentRewriteRange = {
      endNodeId: resolved.endNodeId,
      endOffset: resolved.endOffset,
      startNodeId: resolved.startNodeId,
      startOffset: resolved.startOffset,
    };
    const remoteConflict = this.hasRemoteStreamingConflict(selectionRange, resolved.targetNodeIds);
    if (remoteConflict) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        remoteConflict,
        resolved.targetNodeIds,
      );
    }

    // A second local stream targeting the same durable block would race the
    // first stream even when its capture range is disjoint: the current Yjs
    // stream writer and region marker are block-scoped. Keep the first stream
    // intact and ask the caller to retry after it settles.
    for (const active of this.rewriteSessions.values()) {
      if (active.status !== 'streaming') continue;
      const overlap = hasOverlappingRewriteRanges(
        {
          ...active.selectionRange,
          targetNodeIds: active.selectionTargetNodeIds,
        },
        { ...selectionRange, targetNodeIds: resolved.targetNodeIds },
      );
      const localConflict =
        overlap === true
          ? 'stream-session-conflict'
          : hasOverlappingNodeIds(active.selectionTargetNodeIds, resolved.targetNodeIds)
            ? 'stream-session-busy'
            : undefined;
      if (localConflict) {
        return this.createStandaloneStreamResult(
          sessionId,
          generationId,
          'conflict',
          localConflict,
          resolved.targetNodeIds,
        );
      }
    }

    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'stopped',
        'CollaborativeAgentEditor lexical editor is unavailable.',
        resolved.targetNodeIds,
      );
    }

    const anchor: AgentCaretAnchor = {
      nodeId: resolved.startNodeId,
      offset: resolved.startOffset,
    };
    let regionAnchorPosition: RelativePosition | undefined;
    let needsBoundarySeparator = false;
    lexicalEditor?.getEditorState().read(() => {
      if (!resolved.endNodeId || resolved.endOffset === undefined) return;
      const startBlock = $findNodeById(resolved.startNodeId!);
      const endBlock = $findNodeById(resolved.endNodeId);
      if (!startBlock || !endBlock || startBlock === endBlock) return;
      const endSuffix = endBlock.getTextContent().slice(resolved.endOffset);
      needsBoundarySeparator = endSuffix.length > 0 && !/^\s/u.test(endSuffix);
    });
    const selectionSnapshot = {
      anchor: {
        key: resolved.selection.anchor.key,
        offset: resolved.selection.anchor.offset,
        type: resolved.selection.anchor.type,
      },
      focus: {
        key: resolved.selection.focus.key,
        offset: resolved.selection.focus.offset,
        type: resolved.selection.focus.type,
      },
    };
    let didStart = false;
    let boundarySeparatorKey: string | undefined;
    try {
      lexicalEditor.update(
        () => {
          const startNode = $getNodeByKey(selectionSnapshot.anchor.key);
          const endNode = $getNodeByKey(selectionSnapshot.focus.key);
          if (!startNode || !endNode || !startNode.isAttached() || !endNode.isAttached()) return;

          const range = $createRangeSelection();
          range.anchor.set(
            selectionSnapshot.anchor.key,
            selectionSnapshot.anchor.offset,
            selectionSnapshot.anchor.type,
          );
          range.focus.set(
            selectionSnapshot.focus.key,
            selectionSnapshot.focus.offset,
            selectionSnapshot.focus.type,
          );
          $setSelection(range);
          range.removeText();

          // Establish the protected region in the same transaction as the
          // selection removal. A zero-length durable block/offset range
          // closes the first-token race: peers cannot type/paste/delete into
          // the AI caret while the model is still waiting to emit its first
          // chunk. The marker lives in NodeState, so it is transparent to
          // text/Markdown projections and survives Yjs reload.
          const block = $findNodeById(anchor.nodeId);
          if (!block) return;
          $markNodeAsStreamingGenerationRegion(block, {
            generationId,
            requestId: this.requestId,
            sessionId,
          });
          $setStreamingGenerationRegionRange(block, { length: 0, startOffset: anchor.offset });
          if (needsBoundarySeparator) {
            const separator = insertPlainTextAtBlockOffset(block, anchor.offset, ' ');
            if (!separator) return;
            boundarySeparatorKey = separator.getKey();
          }
          $setSelection(null);
          didStart = true;
        },
        // The remove-and-stream sequence should be one user-visible undo
        // action while chunks continue arriving in their own Yjs updates.
        { discrete: true, tag: HISTORY_PUSH_TAG },
      );
    } catch (error) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'failed',
        error instanceof Error ? error.message : 'stream-start-failed',
        resolved.targetNodeIds,
      );
    }

    if (!didStart) {
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'conflict',
        'stream-generation-region-not-created',
        resolved.targetNodeIds,
      );
    }

    // Capture the anchor after the selected text has been removed. Creating it
    // before removal can point at an item that is deleted by the rewrite; Yjs
    // then falls back to the old numeric index and cannot follow prefix edits.
    // The post-removal suffix item is durable and shifts naturally when the
    // human-authored prefix grows or shrinks.
    lexicalEditor.getEditorState().read(() => {
      const yjsState = this.getYjsServiceState();
      const block = $findNodeById(anchor.nodeId);
      if (!yjsState || !block) return;
      const point = getBlockPoint(block, anchor.offset, 'start');
      if (!point) return;
      regionAnchorPosition =
        createRelativePositionForLexicalPoint(point, yjsState.binding) ?? undefined;
    });

    const currentTargetTexts = this.readStreamingTargetTexts(resolved.targetNodeIds).texts;
    const knownMissingTargetNodeIds = new Set<string>();
    for (const nodeId of resolved.targetNodeIds) {
      if (!currentTargetTexts.has(nodeId)) knownMissingTargetNodeIds.add(nodeId);
    }
    // The containing start block must survive start; otherwise there is no
    // durable place where a later chunk could be safely inserted.
    if (!currentTargetTexts.has(anchor.nodeId)) {
      this.clearStreamingRegionMetadata(sessionId);
      return this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'stopped',
        'stream-generation-region-not-created',
        resolved.targetNodeIds,
      );
    }

    const state: CollaborativeRewriteStreamState = {
      affectedNodeIds: [...resolved.targetNodeIds],
      ...(boundarySeparatorKey ? { boundarySeparatorKey } : {}),
      caret: anchor,
      chunks: new Map(),
      expectedBlockTexts: currentTargetTexts,
      generatedText: '',
      generationId,
      knownMissingTargetNodeIds,
      lastResult: this.createStandaloneStreamResult(
        sessionId,
        generationId,
        'streaming',
        undefined,
        resolved.targetNodeIds,
        0,
        anchor,
      ),
      lastSequence: -1,
      ...(input.model ? { model: input.model } : {}),
      originalTextHash: input.expectedTextHash,
      ...(provenanceSessionId ? { provenanceSessionId } : {}),
      ...(input.provider ? { provider: input.provider } : {}),
      ...(regionAnchorPosition ? { regionAnchorPosition } : {}),
      regionStartOffset: anchor.offset,
      requestId: this.requestId,
      selectionRange,
      selectionTargetNodeIds: [...resolved.targetNodeIds],
      sessionId,
      status: 'streaming',
      ...(input.turnIndex !== undefined ? { turnIndex: input.turnIndex } : {}),
    };
    this.rewriteSessions.set(sessionId, state);
    this.publishStreamingAwareness(state, 'writing');
    return this.copyStreamingResult(state.lastResult);
  }

  /** Append one idempotent text chunk through a normal Lexical/Yjs update. */
  async appendRewriteChunk(
    input: CollaborativeRewriteStreamAppendInput,
  ): Promise<CollaborativeRewriteStreamResult> {
    const sessionId = isValidStreamId(input?.sessionId) ? input.sessionId.trim() : '';
    const chunkId = isValidStreamId(input?.chunkId) ? input.chunkId.trim() : '';
    const state = this.rewriteSessions.get(sessionId);
    if (!state) {
      return this.createStandaloneStreamResult(sessionId, '', 'failed', 'stream-session-not-found');
    }
    if (!chunkId) return this.streamResultWithError(state, 'chunkId-required', 'failed');

    const chunk = this.getChunkText(input);
    if (chunk === null) return this.streamResultWithError(state, 'chunk-text-required', 'failed');

    const suppliedProvenanceSessionId =
      input.provenanceSessionId === undefined
        ? undefined
        : isValidStreamId(input.provenanceSessionId)
          ? input.provenanceSessionId.trim()
          : '';
    if (input.provenanceSessionId !== undefined && !suppliedProvenanceSessionId) {
      return this.streamResultWithError(state, 'provenanceSessionId-invalid', 'failed');
    }
    if (
      suppliedProvenanceSessionId !== undefined &&
      state.provenanceSessionId !== undefined &&
      suppliedProvenanceSessionId !== state.provenanceSessionId
    ) {
      return this.streamResultWithError(state, 'provenanceSessionId-mismatch', 'failed');
    }
    if (
      input.turnIndex !== undefined &&
      (!Number.isSafeInteger(input.turnIndex) || input.turnIndex < 0)
    ) {
      return this.streamResultWithError(state, 'turnIndex-invalid', 'failed');
    }
    if (
      input.turnIndex !== undefined &&
      state.turnIndex !== undefined &&
      input.turnIndex !== state.turnIndex
    ) {
      return this.streamResultWithError(state, 'turnIndex-mismatch', 'failed');
    }
    if (state.provenanceSessionId === undefined && suppliedProvenanceSessionId !== undefined) {
      state.provenanceSessionId = suppliedProvenanceSessionId;
    }
    if (state.turnIndex === undefined && input.turnIndex !== undefined) {
      state.turnIndex = input.turnIndex;
    }

    const previousChunk = state.chunks.get(chunkId);
    if (previousChunk) {
      if (
        previousChunk.text !== chunk ||
        (previousChunk.sequence !== undefined &&
          input.sequence !== undefined &&
          previousChunk.sequence !== input.sequence)
      ) {
        return this.streamResultWithError(state, 'chunk-id-reused', 'failed');
      }
      // The chunk already committed; never insert it twice, even if a caller
      // retries after the transport response was lost.
      return this.copyStreamingResult(state.lastResult);
    }
    if (state.status !== 'streaming') return this.copyStreamingResult(state.lastResult);
    if (!this.isReadyForStreaming()) {
      return this.stopStreamingSession(state, 'stopped', 'stream-stopped-provider-disconnected');
    }
    if (input.sequence !== undefined) {
      if (!Number.isSafeInteger(input.sequence) || input.sequence < 0) {
        return this.streamResultWithError(state, 'chunk-sequence-invalid', 'failed');
      }
      const expected = state.lastSequence < 0 ? input.sequence : state.lastSequence + 1;
      if (input.sequence !== expected) {
        return this.streamResultWithError(state, 'chunk-sequence-out-of-order', 'failed');
      }
    }
    const targetIssue = this.getStreamingTargetIssue(state);
    if (targetIssue) {
      return this.stopStreamingSession(state, 'conflict', targetIssue);
    }

    const insertionOffset = this.getStreamingInsertionOffset(state);
    if (insertionOffset === null) {
      return this.stopStreamingSession(state, 'conflict', 'stream-caret-invalid');
    }
    const regionStartOffset =
      state.generatedText.length > 0
        ? insertionOffset - state.generatedText.length
        : insertionOffset;
    if (regionStartOffset < 0) {
      return this.stopStreamingSession(state, 'conflict', 'stream-caret-invalid');
    }

    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) {
      return this.stopStreamingSession(state, 'stopped', 'stream-lexical-editor-unavailable');
    }

    let didAppend = chunk.length === 0;
    const removeBoundarySeparator = Boolean(state.boundarySeparatorKey && /\s$/u.test(chunk));
    try {
      lexicalEditor.update(
        () => {
          const block = $findNodeById(state.caret.nodeId);
          if (!block) return;
          if (removeBoundarySeparator && state.boundarySeparatorKey) {
            $getNodeByKey(state.boundarySeparatorKey)?.remove();
          }
          didAppend =
            chunk.length === 0 ||
            insertStreamingTextAtBlockOffset(block, insertionOffset, chunk, state, {
              createdAt: new Date().toISOString(),
              generationId: state.generationId,
              model: state.model,
              provider: state.provider,
              requestId: state.requestId,
              sessionId: state.provenanceSessionId,
              turnIndex: state.turnIndex,
            });
          if (didAppend) {
            if (removeBoundarySeparator) state.boundarySeparatorKey = undefined;
            $setStreamingGenerationRegionRange(block, {
              length: state.generatedText.length + chunk.length,
              startOffset: regionStartOffset,
            });
            $setSelection(null);
          }
        },
        { discrete: true },
      );
    } catch (error) {
      return this.stopStreamingSession(
        state,
        'stopped',
        error instanceof Error ? error.message : 'stream-chunk-failed',
      );
    }
    if (!didAppend) return this.stopStreamingSession(state, 'conflict', 'stream-caret-invalid');

    state.chunks.set(chunkId, { sequence: input.sequence, text: chunk });
    state.lastSequence = input.sequence ?? state.lastSequence + 1;
    state.generatedText += chunk;
    state.regionStartOffset = regionStartOffset;
    state.caret = {
      nodeId: state.caret.nodeId,
      offset: insertionOffset + chunk.length,
    };
    state.expectedBlockTexts = this.readStreamingTargetTexts(state.selectionTargetNodeIds).texts;
    const stateVector = this.getStateVectorSafely();
    state.lastResult = this.createStandaloneStreamResult(
      state.sessionId,
      state.generationId,
      'streaming',
      undefined,
      state.affectedNodeIds,
      state.chunks.size,
      state.caret,
      stateVector ?? undefined,
    );
    this.publishStreamingAwareness(state, 'writing');
    await moment();
    return this.copyStreamingResult(state.lastResult);
  }

  /** Finalize a stream, remove temporary protection, and return Yjs proof. */
  async finalizeRewriteSession(
    input: CollaborativeRewriteStreamFinalizeInput,
  ): Promise<CollaborativeRewriteStreamResult> {
    const sessionId = isValidStreamId(input?.sessionId) ? input.sessionId.trim() : '';
    const state = this.rewriteSessions.get(sessionId);
    if (!state) {
      return this.recoverRewriteSession({ sessionId, requestId: this.requestId });
    }
    if (state.status !== 'streaming') return this.copyStreamingResult(state.lastResult);
    if (!this.isReadyForStreaming()) {
      return this.stopStreamingSession(state, 'stopped', 'stream-stopped-provider-disconnected');
    }
    const targetIssue = this.getStreamingTargetIssue(state);
    if (targetIssue) {
      return this.stopStreamingSession(state, 'conflict', targetIssue);
    }

    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor)
      return this.stopStreamingSession(state, 'stopped', 'stream-lexical-editor-unavailable');

    try {
      lexicalEditor.update(
        () => {
          if (state.generatedText.length === 0 && state.boundarySeparatorKey) {
            $getNodeByKey(state.boundarySeparatorKey)?.remove();
            state.boundarySeparatorKey = undefined;
          }
          const root = $getRoot();
          const visit = (node: LexicalNode): void => {
            $clearStreamingGenerationRegion(node, state.sessionId);
            if ($isElementNode(node)) node.getChildren().forEach(visit);
          };
          visit(root);
          $setSelection(null);
        },
        // Keep cleanup in the same Yjs capture window as the streamed text;
        // tagging this transaction would make metadata removal a separate
        // top undo item and force the user to undo twice.
        { discrete: true },
      );
    } catch (error) {
      return this.stopStreamingSession(
        state,
        'stopped',
        error instanceof Error ? error.message : 'stream-finalize-failed',
      );
    }

    state.status = 'applied';
    state.lastResult = this.createStandaloneStreamResult(
      state.sessionId,
      state.generationId,
      'applied',
      undefined,
      state.affectedNodeIds,
      state.chunks.size,
      state.caret,
      this.getStateVectorSafely() ?? undefined,
    );
    try {
      this.clearAwareness();
    } catch {
      // A successful document commit must not become a failed stream solely
      // because a custom awareness transport is unavailable during teardown.
    }
    await moment();
    return this.copyStreamingResult(state.lastResult);
  }

  /** Abort without rolling back already-visible chunks. */
  async abortRewriteSession(
    input: CollaborativeRewriteStreamAbortInput,
  ): Promise<CollaborativeRewriteStreamResult> {
    const sessionId = isValidStreamId(input?.sessionId) ? input.sessionId.trim() : '';
    const state = this.rewriteSessions.get(sessionId);
    if (!state) {
      return this.recoverRewriteSession({ sessionId, requestId: this.requestId });
    }
    if (state.status !== 'streaming') return this.copyStreamingResult(state.lastResult);

    const reason = isValidStreamId(input?.reason) ? input.reason.trim() : 'stream-aborted';
    const lexicalEditor = this.getLexicalEditor();
    if (lexicalEditor) {
      try {
        lexicalEditor.update(
          () => {
            if (state.generatedText.length === 0 && state.boundarySeparatorKey) {
              $getNodeByKey(state.boundarySeparatorKey)?.remove();
              state.boundarySeparatorKey = undefined;
            }
            const visit = (node: LexicalNode): void => {
              $clearStreamingGenerationRegion(node, state.sessionId);
              if ($isElementNode(node)) node.getChildren().forEach(visit);
            };
            visit($getRoot());
            $setSelection(null);
          },
          { discrete: true },
        );
      } catch {
        // Abort is best-effort protection cleanup; importantly, it never
        // reintroduces the removed original text.
      }
    }
    return this.stopStreamingSession(state, 'aborted', reason);
  }

  /**
   * Safely stop a stream left behind by a crashed/reloaded Agent process.
   * Only a unique persisted region carrying this request/session/generation
   * identity is cleared. The partial generated text is retained and no old
   * selection is restored, so recovery can never resurrect the replacement.
   */
  async recoverRewriteSession(
    input: CollaborativeRewriteStreamRecoveryInput,
  ): Promise<CollaborativeRewriteStreamResult> {
    const sessionId = isValidStreamId(input?.sessionId) ? input.sessionId.trim() : '';
    const requestedGenerationId =
      input?.generationId === undefined ? undefined : input.generationId.trim();
    const requestedRequestId = input?.requestId === undefined ? this.requestId : input.requestId;
    const cached = this.recoveredRewriteSessions.get(sessionId);
    if (cached) return this.copyStreamingResult(cached);
    if (!sessionId || !isValidStreamId(requestedRequestId)) {
      return this.createStandaloneStreamResult(
        sessionId,
        requestedGenerationId ?? '',
        'failed',
        'stream-recovery-identity-required',
      );
    }
    if (requestedRequestId !== this.requestId) {
      return this.createStandaloneStreamResult(
        sessionId,
        requestedGenerationId ?? '',
        'failed',
        'requestId does not match this Agent session.',
      );
    }
    if (!this.isReadyForStreaming()) {
      return this.createStandaloneStreamResult(
        sessionId,
        requestedGenerationId ?? '',
        'stopped',
        'CollaborativeAgentEditor must be synced before stream recovery.',
      );
    }

    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) {
      return this.createStandaloneStreamResult(
        sessionId,
        requestedGenerationId ?? '',
        'stopped',
        'stream-lexical-editor-unavailable',
      );
    }

    let matchedGenerationId = requestedGenerationId ?? '';
    let regionBlock: LexicalNode | null = null;
    let regionBlockId: string | undefined;
    let regionStartOffset: number | undefined;
    let regionLength: number | undefined;
    let matchedNodes = 0;
    lexicalEditor.getEditorState().read(() => {
      const visit = (node: LexicalNode): void => {
        const region = $getStreamingGenerationRegion(node);
        if (
          region?.sessionId === sessionId &&
          region.requestId === requestedRequestId &&
          (requestedGenerationId === undefined || region.generationId === requestedGenerationId)
        ) {
          matchedNodes += 1;
          matchedGenerationId ||= region.generationId;
          if (region.startOffset !== undefined && region.length !== undefined) {
            if (regionBlock) {
              // More than one durable range for one identity is ambiguous;
              // do not mutate any node in that case.
              regionBlock = null;
            } else {
              regionBlock = node;
              regionBlockId = $getNodeId(node);
              regionStartOffset = region.startOffset;
              regionLength = region.length;
            }
          }
        }
        if ($isElementNode(node)) node.getChildren().forEach(visit);
      };
      visit($getRoot());
    });

    if (matchedNodes === 0) {
      return this.createStandaloneStreamResult(
        sessionId,
        matchedGenerationId,
        'failed',
        'stream-session-not-found',
      );
    }
    if (!regionBlock && regionStartOffset !== undefined) {
      return this.createStandaloneStreamResult(
        sessionId,
        matchedGenerationId,
        'failed',
        'stream-recovery-ambiguous-region',
      );
    }

    try {
      lexicalEditor.update(
        () => {
          const visit = (node: LexicalNode): void => {
            const region = $getStreamingGenerationRegion(node);
            if (
              region?.sessionId === sessionId &&
              region.requestId === requestedRequestId &&
              region.generationId === matchedGenerationId
            ) {
              $clearStreamingGenerationRegion(
                node,
                sessionId,
                matchedGenerationId,
                requestedRequestId,
              );
            }
            if ($isElementNode(node)) node.getChildren().forEach(visit);
          };
          visit($getRoot());
        },
        { discrete: true },
      );
    } catch (error) {
      return this.createStandaloneStreamResult(
        sessionId,
        matchedGenerationId,
        'stopped',
        error instanceof Error ? error.message : 'stream-recovery-cleanup-failed',
      );
    }
    const affectedNodeIds = regionBlockId ? [regionBlockId] : [];
    const caret =
      regionBlockId && regionStartOffset !== undefined && regionLength !== undefined
        ? {
            nodeId: regionBlockId,
            offset: regionStartOffset + regionLength,
          }
        : undefined;
    const result = this.createStandaloneStreamResult(
      sessionId,
      matchedGenerationId,
      'stopped',
      'stream-recovered-after-restart',
      affectedNodeIds,
      0,
      caret?.nodeId ? caret : undefined,
      this.getStateVectorSafely() ?? undefined,
    );
    this.recoveredRewriteSessions.set(sessionId, result);
    try {
      this.clearAwareness();
    } catch {
      // Recovery remains successful when an old awareness socket is gone.
    }
    await moment();
    return this.copyStreamingResult(result);
  }

  /** Page-facing name for crash/reload cleanup of a persisted stream region. */
  cleanupStreamingRewrite(input: CollaborativeRewriteStreamRecoveryInput) {
    return this.recoverRewriteSession(input);
  }

  // Friendly aliases for browser/Node integrations that use "streaming"
  // terminology instead of "rewrite session".
  async startStreamingRewrite(
    input: CollaborativeRewriteStreamStartInput,
  ): Promise<CollaborativeRewriteStreamSession> {
    const started = await this.startRewriteSession(input);
    if (started.status !== 'streaming') {
      throw new Error(started.error ?? 'stream-start-failed');
    }

    const sessionId = started.sessionId;
    return {
      abort: (reason?: string) => this.abortRewriteSession({ reason, sessionId }),
      append: (chunk) => this.appendRewriteChunk({ ...chunk, sessionId }),
      finalize: () => this.finalizeRewriteSession({ sessionId }),
      generationId: started.generationId,
      requestId: started.requestId,
      sessionId,
    };
  }

  appendStreamingRewrite(input: CollaborativeRewriteStreamAppendInput) {
    return this.appendRewriteChunk(input);
  }

  finalizeStreamingRewrite(input: CollaborativeRewriteStreamFinalizeInput) {
    return this.finalizeRewriteSession(input);
  }

  abortStreamingRewrite(input: CollaborativeRewriteStreamAbortInput) {
    return this.abortRewriteSession(input);
  }

  private createStandaloneStreamResult(
    sessionId: string,
    generationId: string,
    status: CollaborativeRewriteStreamStatus,
    error?: string,
    affectedNodeIds: ReadonlyArray<string> = [],
    sequence = 0,
    caret?: AgentCaretAnchor,
    stateVector?: string,
  ): CollaborativeRewriteStreamResult {
    return {
      affectedNodeIds: [...affectedNodeIds],
      ...(caret ? { caret: { ...caret } } : {}),
      ...(error ? { error } : {}),
      generationId,
      requestId: this.requestId,
      sequence,
      sessionId,
      ...(stateVector ? { stateVector } : {}),
      status,
    };
  }

  private copyStreamingResult(
    result: CollaborativeRewriteStreamResult,
  ): CollaborativeRewriteStreamResult {
    return {
      ...result,
      affectedNodeIds: [...result.affectedNodeIds],
      ...(result.caret ? { caret: { ...result.caret } } : {}),
    };
  }

  private streamResultWithError(
    state: CollaborativeRewriteStreamState,
    error: string,
    status: CollaborativeRewriteStreamStatus,
  ): CollaborativeRewriteStreamResult {
    const result = this.createStandaloneStreamResult(
      state.sessionId,
      state.generationId,
      status,
      error,
      state.affectedNodeIds,
      state.chunks.size,
      state.caret,
      this.getStateVectorSafely() ?? undefined,
    );
    // Validation errors do not end a stream. The caller can retry the same
    // chunk with the original idempotent identity after correcting it; keep
    // the last committed streaming result as the session's canonical state.
    return this.copyStreamingResult(result);
  }

  private isReadyForStreaming(): boolean {
    return !this.disconnected && this.connected && this.synced && !this.transportUnavailable;
  }

  private getChunkText(input: CollaborativeRewriteStreamAppendInput): string | null {
    if (input.chunk !== undefined && typeof input.chunk !== 'string') return null;
    if (input.text !== undefined && typeof input.text !== 'string') return null;
    if (input.chunk !== undefined && input.text !== undefined && input.chunk !== input.text) {
      return null;
    }
    const text = input.chunk ?? input.text;
    return text === undefined ? null : text;
  }

  private readStreamingTargetTexts(targetNodeIds: ReadonlyArray<string>): {
    duplicateNodeIds: Set<string>;
    missingNodeIds: Set<string>;
    texts: Map<string, string>;
  } {
    const texts = new Map<string, string>();
    const missingNodeIds = new Set<string>();
    const duplicateNodeIds = new Set<string>();
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) {
      targetNodeIds.forEach((nodeId) => missingNodeIds.add(nodeId));
      return { duplicateNodeIds, missingNodeIds, texts };
    }

    lexicalEditor.getEditorState().read(() => {
      for (const nodeId of targetNodeIds) {
        const nodes = $findNodesById(nodeId).filter((node) => node.isAttached());
        if (nodes.length !== 1) {
          if (nodes.length > 1) duplicateNodeIds.add(nodeId);
          else missingNodeIds.add(nodeId);
          continue;
        }
        texts.set(nodeId, nodes[0].getTextContent());
      }
    });
    return { duplicateNodeIds, missingNodeIds, texts };
  }

  /** Read the durable region marker and generated leaves in one editor read. */
  private readStreamingRegionSnapshot(state: CollaborativeRewriteStreamState): {
    generatedNodeCount: number;
    generatedStartOffset?: number;
    generatedText: string;
    marker?: {
      generationId: string;
      length?: number;
      requestId?: string;
      sessionId: string;
      startOffset?: number;
    };
    generatedEndOffset?: number;
    generatedContiguous: boolean;
  } {
    const snapshot: {
      generatedNodeCount: number;
      generatedStartOffset?: number;
      generatedText: string;
      marker?: {
        generationId: string;
        length?: number;
        requestId?: string;
        sessionId: string;
        startOffset?: number;
      };
      generatedEndOffset?: number;
      generatedContiguous: boolean;
    } = {
      generatedNodeCount: 0,
      generatedText: '',
      generatedContiguous: true,
    };
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) return snapshot;

    lexicalEditor.getEditorState().read(() => {
      const block = $findNodeById(state.caret.nodeId);
      if (!block) return;

      const marker = $getStreamingGenerationRegion(block);
      if (marker) snapshot.marker = marker;

      const generatedSegments = getLinearTextSegments(block).filter((segment) => {
        if (!$isTextNode(segment.node)) return false;
        const region = $getStreamingGenerationRegion(segment.node);
        return (
          region?.sessionId === state.sessionId &&
          region.generationId === state.generationId &&
          region.startOffset === undefined &&
          region.length === undefined
        );
      });
      if (generatedSegments.length === 0) return;

      snapshot.generatedNodeCount = generatedSegments.length;
      snapshot.generatedStartOffset = generatedSegments[0].start;
      snapshot.generatedEndOffset = generatedSegments.at(-1)!.end;
      snapshot.generatedText = generatedSegments
        .map((segment) => segment.node.getTextContent())
        .join('');
      snapshot.generatedContiguous =
        snapshot.generatedEndOffset - snapshot.generatedStartOffset ===
        snapshot.generatedText.length;
    });
    return snapshot;
  }

  /** Resolve a node's current linear offset inside the streaming block. */
  private readStreamingNodeOffset(
    state: CollaborativeRewriteStreamState,
    nodeKey: string,
  ): number | null {
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) return null;
    let offset: number | null = null;
    lexicalEditor.getEditorState().read(() => {
      const block = $findNodeById(state.caret.nodeId);
      if (!block) return;
      const segment = getLinearTextSegments(block).find(
        (candidate) => candidate.node.getKey() === nodeKey,
      );
      if (segment) offset = segment.start;
    });
    return offset;
  }

  /**
   * Resolve the start of a zero-length region through its Yjs anchor. The
   * relative position tracks edits to the human prefix, whereas the generated
   * leaves below provide an exact boundary once the first chunk exists.
   */
  private readStreamingRelativeAnchorOffset(state: CollaborativeRewriteStreamState): number | null {
    const regionAnchorPosition = state.regionAnchorPosition;
    if (!regionAnchorPosition) return null;
    const yjsState = this.getYjsServiceState();
    const lexicalEditor = yjsState?.binding.editor;
    if (!yjsState || !lexicalEditor) return null;

    let offset: number | null = null;
    lexicalEditor.getEditorState().read(() => {
      const points = getAnchorAndFocusCollabNodesForUserState(yjsState.binding, {
        anchorPos: regionAnchorPosition,
        awarenessData: {},
        color: '#7c3aed',
        focusPos: regionAnchorPosition,
        focusing: true,
        name: 'AI Agent',
      });
      const node = points.anchorCollabNode?.getNode();
      const block = $findNodeById(state.caret.nodeId);
      if (!node || !block) return;
      const point = {
        getNode: () => node,
        offset: points.anchorOffset,
        type: $isElementNode(node) ? ('element' as const) : ('text' as const),
      };
      offset = getBlockOffset(point, block);
    });
    return offset;
  }

  /** Compute the current insertion boundary after prefix edits and retries. */
  private getStreamingInsertionOffset(state: CollaborativeRewriteStreamState): number | null {
    const snapshot = this.readStreamingRegionSnapshot(state);
    if (snapshot.generatedNodeCount > 0) {
      if (!snapshot.generatedContiguous || snapshot.generatedEndOffset === undefined) return null;
      return snapshot.generatedEndOffset;
    }

    if (state.boundarySeparatorKey) {
      const separatorOffset = this.readStreamingNodeOffset(state, state.boundarySeparatorKey);
      if (separatorOffset !== null) return separatorOffset;
    }

    return this.readStreamingRelativeAnchorOffset(state) ?? state.regionStartOffset;
  }

  private getStreamingTargetIssue(
    state: CollaborativeRewriteStreamState,
  ): 'generation_conflict' | 'region_missing' | null {
    const region = this.readStreamingRegionSnapshot(state);
    if (
      !region.marker ||
      region.marker.sessionId !== state.sessionId ||
      region.marker.generationId !== state.generationId ||
      (region.marker.requestId !== undefined && region.marker.requestId !== state.requestId) ||
      region.marker.length !== state.generatedText.length
    ) {
      return 'region_missing';
    }
    const current = this.readStreamingTargetTexts(state.selectionTargetNodeIds);
    if (current.duplicateNodeIds.size > 0) return 'generation_conflict';

    // Generated chunks are individually marked. If a user/peer removes the
    // entire generated run while the block itself survives, the durable block
    // range still exists but the region content is gone. Report that distinct
    // condition so the worker can settle the request as an explicit user
    // cancellation rather than a generic same-target edit conflict.
    const hasGeneratedNodes = region.generatedNodeCount > 0;

    if (state.generatedText.length > 0) {
      if (!hasGeneratedNodes) return 'region_missing';
      if (!region.generatedContiguous || region.generatedText !== state.generatedText) {
        return 'generation_conflict';
      }
    }

    for (const nodeId of state.selectionTargetNodeIds) {
      const wasMissing = state.knownMissingTargetNodeIds.has(nodeId);
      const expected = state.expectedBlockTexts.get(nodeId);
      const actual = current.texts.get(nodeId);
      if (wasMissing) {
        // A target removed by the initial selection operation remains outside
        // the protected live region. If it reappears, another client has
        // mutated the target and the session must not guess how to merge it.
        if (actual !== undefined) return 'generation_conflict';
        continue;
      }
      if (actual === undefined) return 'generation_conflict';
      // The host block is intentionally editable outside the generated run.
      // Its whole text therefore cannot be compared with the post-start
      // snapshot; generated leaves and the durable region marker above are the
      // authoritative proof for that block.
      if (nodeId !== state.caret.nodeId && expected !== actual) {
        return 'generation_conflict';
      }
    }
    return null;
  }

  private hasRemoteStreamingConflict(
    selectionRange: AgentRewriteRange,
    targetNodeIds: ReadonlyArray<string>,
  ): 'stream-session-busy' | 'stream-session-conflict' | null {
    const local = this.provider.awareness.getLocalState();
    for (const state of this.provider.awareness.getStates().values()) {
      if (!state || state === local) continue;
      const data = state.awarenessData as {
        role?: unknown;
        sessionId?: unknown;
        status?: unknown;
        selectionRange?: unknown;
        targetNodeIds?: unknown;
      };
      if (
        data.role !== 'agent' ||
        typeof data.sessionId !== 'string' ||
        !ACTIVE_STREAM_AWARENESS_STATUSES.has(data.status as AgentAwarenessStatus) ||
        !Array.isArray(data.targetNodeIds) ||
        !data.targetNodeIds.every((nodeId): nodeId is string => typeof nodeId === 'string')
      ) {
        continue;
      }

      const remoteRange = isAgentRewriteRange(data.selectionRange)
        ? data.selectionRange
        : undefined;
      if (remoteRange) {
        const overlap = hasOverlappingRewriteRanges(
          { ...selectionRange, targetNodeIds },
          { ...remoteRange, targetNodeIds: data.targetNodeIds },
        );
        if (overlap === true) return 'stream-session-conflict';
        if (overlap === false) {
          if (hasOverlappingNodeIds(targetNodeIds, data.targetNodeIds)) {
            return 'stream-session-busy';
          }
          continue;
        }
      }

      // Older Agent clients only publish the block projection. Keep the
      // conservative block-id gate for that wire shape. `busy` is distinct
      // from a proven overlap so callers can retry without surfacing a false
      // overlap warning, while unrelated blocks remain available.
      if (hasOverlappingNodeIds(targetNodeIds, data.targetNodeIds)) {
        return 'stream-session-busy';
      }
    }
    return null;
  }

  private getRelativePositionForCaret(caret: AgentCaretAnchor): RelativePosition | null {
    const service = this.getYjsServiceState();
    const lexicalEditor = service?.binding.editor;
    if (!service || !lexicalEditor) return null;

    let position: RelativePosition | null = null;
    lexicalEditor.getEditorState().read(() => {
      const block = $findNodeById(caret.nodeId);
      if (!block) return;
      const point = getBlockPoint(block, caret.offset, 'end');
      if (!point || !isValidLexicalPoint(point.key, point.offset, point.type)) return;
      position = createRelativePositionForLexicalPoint(point, service.binding);
    });
    return position;
  }

  private publishStreamingAwareness(
    state: CollaborativeRewriteStreamState,
    status: Extract<AgentAwarenessStatus, 'syncing' | 'thinking' | 'writing'>,
  ): void {
    if (this.disconnected) return;
    try {
      const position = this.getRelativePositionForCaret(state.caret);
      this.setAgentAwareness({
        ...(position ? { anchorPos: position, focusPos: position } : {}),
        caret: state.caret,
        documentId: this.documentId,
        generationId: state.generationId,
        requestId: this.requestId,
        selectionRange: state.selectionRange,
        sessionId: state.sessionId,
        status,
        targetNodeIds: state.selectionTargetNodeIds,
      });
    } catch {
      // Awareness is advisory. A document chunk that has already committed
      // must remain successful if a provider temporarily rejects a cursor
      // update.
    }
  }

  private stopStreamingSession(
    state: CollaborativeRewriteStreamState,
    status: Extract<CollaborativeRewriteStreamStatus, 'aborted' | 'conflict' | 'stopped'>,
    error: string,
  ): CollaborativeRewriteStreamResult {
    if (state.status !== 'streaming') return this.copyStreamingResult(state.lastResult);
    this.clearStreamingRegionMetadata(state.sessionId);
    state.status = status;
    state.lastResult = this.createStandaloneStreamResult(
      state.sessionId,
      state.generationId,
      status,
      error,
      state.affectedNodeIds,
      state.chunks.size,
      state.caret,
      this.getStateVectorSafely() ?? undefined,
    );
    try {
      this.clearAwareness();
    } catch {
      // Keep the terminal state even if transport teardown is already in
      // progress.
    }
    return this.copyStreamingResult(state.lastResult);
  }

  private clearStreamingRegionMetadata(sessionId: string): void {
    const lexicalEditor = this.getLexicalEditor();
    if (!lexicalEditor) return;
    try {
      lexicalEditor.update(
        () => {
          const visit = (node: LexicalNode): void => {
            $clearStreamingGenerationRegion(node, sessionId);
            if ($isElementNode(node)) node.getChildren().forEach(visit);
          };
          visit($getRoot());
        },
        { discrete: true },
      );
    } catch {
      // The region may already have been deleted by a structural operation.
    }
  }

  getRewriteResult(requestId = this.requestId): RewriteCommandResult | undefined {
    return this.resultChannel.get(requestId);
  }

  async disconnect(): Promise<void> {
    if (this.disconnected) return;
    for (const session of this.rewriteSessions.values()) {
      if (session.status === 'streaming') {
        this.stopStreamingSession(session, 'stopped', 'stream-stopped-provider-disconnected');
      }
    }
    try {
      this.clearAwareness();
    } catch {
      // Teardown must continue even if a custom provider rejects awareness.
    }
    this.disconnected = true;
    this.connected = false;
    this.synced = false;
    this.syncWaiters.forEach(({ reject }) =>
      reject(new Error('CollaborativeAgentEditor disconnected.')),
    );
    this.syncWaiters.clear();
    this.providerSyncPromise = null;
    this.provider.off('status', this.providerStatusListener);
    this.provider.off('sync', this.providerSyncListener);
    this.provider.disconnect();
    this.kernel.destroy();
    internalStates.delete(this);
    if (this.ownsDoc) this.yjsDoc.destroy();
  }

  private getLexicalEditor(): LexicalEditor | null {
    return this.kernel.getLexicalEditor();
  }

  private readonly providerStatusListener = ({ status }: { status: string }): void => {
    if (this.disconnected) return;
    if (status === 'connected') {
      this.transportUnavailable = false;
      return;
    }
    if (status !== 'disconnected') return;

    this.transportUnavailable = true;
    this.synced = false;
    // A stream owns a live Lexical caret. Once the transport is gone we do
    // not guess whether a queued chunk was accepted by the room. Stop safely
    // at the last committed text and leave that text in place; callers may
    // start a fresh request after reconnecting.
    for (const session of this.rewriteSessions.values()) {
      if (session.status === 'streaming') {
        this.stopStreamingSession(session, 'stopped', 'stream-stopped-provider-disconnected');
      }
    }
    // A non-streaming Agent awareness state is left to the caller; stream
    // awareness was cleared above because its caret is no longer live.
  };

  /**
   * Keep the facade's command gate in sync with provider reconnects. A
   * reconnect-capable provider keeps its initial sync promise pending until a
   * fresh ticket has authenticated and the state-vector barrier completes, so
   * do not reject the worker's wait here on a transient disconnect.
   */
  private readonly providerSyncListener = (isSynced: boolean): void => {
    if (this.disconnected) return;
    this.synced = isSynced;
    this.transportUnavailable = !isSynced;
  };

  private getYjsServiceState() {
    return this.kernel.requireService(IYjsService)?.getState() ?? null;
  }

  private getProviderSyncPromise(): Promise<void> {
    if (this.providerSyncPromise) return this.providerSyncPromise;

    if (typeof this.provider.waitForSync === 'function') {
      this.providerSyncPromise = this.provider.waitForSync();
      return this.providerSyncPromise;
    }

    this.providerSyncPromise = new Promise<void>((resolve, reject) => {
      const onSync = (isSynced: boolean) => {
        if (!isSynced) return;
        this.provider.off('sync', onSync);
        resolve();
      };
      this.provider.on('sync', onSync);
      if (this.disconnected) {
        this.provider.off('sync', onSync);
        reject(new Error('CollaborativeAgentEditor is disconnected.'));
      }
    });
    return this.providerSyncPromise;
  }

  private resolveRelativeSelection(
    selection: SerializedRelativeRewriteSelection,
    binding: NonNullable<ReturnType<CollaborativeAgentEditor['getYjsServiceState']>>['binding'],
    lexicalEditor: LexicalEditor,
  ): ResolvedRewriteSelection | null {
    if (
      typeof selection.baseStateVector !== 'string' ||
      selection.baseStateVector.length === 0 ||
      typeof selection.quotedText !== 'string' ||
      typeof selection.quotedTextHash !== 'string' ||
      selection.quotedTextHash.length === 0 ||
      (selection.startNodeId !== undefined && !isValidNodeId(selection.startNodeId)) ||
      (selection.endNodeId !== undefined && !isValidNodeId(selection.endNodeId)) ||
      !isValidTargetNodeIds(selection.targetNodeIds)
    ) {
      return null;
    }

    let anchorPos: RelativePosition;
    let focusPos: RelativePosition;
    try {
      anchorPos = deserializeRelativePosition(selection.anchorPos);
      focusPos = deserializeRelativePosition(selection.focusPos);
    } catch {
      return null;
    }
    const userState: UserState = {
      anchorPos,
      awarenessData: {},
      color: '#7c3aed',
      focusPos,
      focusing: true,
      name: 'AI Agent',
    };

    let result: ResolvedRewriteSelection | null = null;
    lexicalEditor.getEditorState().read(() => {
      const points = getAnchorAndFocusCollabNodesForUserState(binding, userState);
      const anchorNode = points.anchorCollabNode?.getNode();
      const focusNode = points.focusCollabNode?.getNode();
      if (!anchorNode || !focusNode) return;

      const anchorKey = anchorNode.getKey();
      const focusKey = focusNode.getKey();
      const anchorLexicalNode = $getNodeByKey(anchorKey);
      const focusLexicalNode = $getNodeByKey(focusKey);
      if (!anchorLexicalNode || !focusLexicalNode) return;

      const anchorType = $isElementNode(anchorLexicalNode) ? 'element' : 'text';
      const focusType = $isElementNode(focusLexicalNode) ? 'element' : 'text';
      if (
        !isValidLexicalPoint(anchorKey, points.anchorOffset, anchorType) ||
        !isValidLexicalPoint(focusKey, points.focusOffset, focusType)
      ) {
        return;
      }

      const range = $createRangeSelection();
      setRangePoint(
        range,
        {
          key: anchorKey,
          offset: points.anchorOffset,
          type: anchorType,
        },
        'anchor',
      );
      setRangePoint(
        range,
        {
          key: focusKey,
          offset: points.focusOffset,
          type: focusType,
        },
        'focus',
      );
      let quotedText: string;
      try {
        quotedText = range.getTextContent();
      } catch {
        return;
      }
      if (
        normalizeRewriteText(quotedText) !== normalizeRewriteText(selection.quotedText) ||
        hashRewriteText(quotedText) !== selection.quotedTextHash
      ) {
        return;
      }
      if (!quotedText) return;

      // Relative positions preserve the original anchor/focus direction. The
      // durable IDs on the resolved result, however, use the same logical
      // start/end ordering as RangeSelection and the rewrite command. Keep
      // the selection itself reversed when the user selected backwards.
      const [startLexicalNode, endLexicalNode] = range.isBackward()
        ? [focusLexicalNode, anchorLexicalNode]
        : [anchorLexicalNode, focusLexicalNode];
      const startBlock = getBlockAncestor(startLexicalNode);
      const endBlock = getBlockAncestor(endLexicalNode);
      if (!startBlock || !endBlock) return;
      const startNodeId = startBlock ? $getNodeId(startBlock) : undefined;
      const endNodeId = endBlock ? $getNodeId(endBlock) : undefined;
      if (!startNodeId || !endNodeId) return;
      if (selection.startNodeId && selection.startNodeId !== startNodeId) return;
      if (selection.endNodeId && selection.endNodeId !== endNodeId) return;

      const targetNodeIds = validateTargetBlocks(
        range,
        startBlock,
        endBlock,
        selection.targetNodeIds,
      );
      if (!targetNodeIds) return;
      const startOffset = getBlockOffset(
        range.isBackward() ? range.focus : range.anchor,
        startBlock,
      );
      const endOffset = getBlockOffset(range.isBackward() ? range.anchor : range.focus, endBlock);
      if (startOffset === null || endOffset === null) return;

      result = {
        baseStateVector: selection.baseStateVector,
        endNodeId,
        endOffset,
        isBackward: range.isBackward(),
        quotedText: normalizeRewriteText(quotedText),
        selection: range,
        startNodeId,
        startOffset,
        targetNodeIds,
        stateVectorDrifted: getStateVectorDrift(
          this.getStateVectorSafely(),
          selection.baseStateVector,
        ),
      };
    });

    return result;
  }

  private resolveBlockSelection(
    selection: BlockRewriteSelection,
    lexicalEditor: LexicalEditor,
  ): ResolvedRewriteSelection | null {
    if (
      !isValidNodeId(selection.startNodeId) ||
      !isValidNodeId(selection.endNodeId) ||
      !Number.isSafeInteger(selection.startOffset) ||
      selection.startOffset < 0 ||
      !Number.isSafeInteger(selection.endOffset) ||
      selection.endOffset < 0 ||
      typeof selection.quotedText !== 'string' ||
      (selection.quotedTextHash !== undefined && typeof selection.quotedTextHash !== 'string') ||
      (selection.baseStateVector !== undefined && typeof selection.baseStateVector !== 'string') ||
      !isValidTargetNodeIds(selection.targetNodeIds)
    ) {
      return null;
    }

    let result: ResolvedRewriteSelection | null = null;
    lexicalEditor.getEditorState().read(() => {
      const startBlock = $findNodeById(selection.startNodeId);
      const endBlock = $findNodeById(selection.endNodeId);
      if (
        !startBlock ||
        !endBlock ||
        $findNodesById(selection.startNodeId).length !== 1 ||
        $findNodesById(selection.endNodeId).length !== 1 ||
        !$isNodeIdentityBlockTarget(startBlock) ||
        !$isNodeIdentityBlockTarget(endBlock)
      ) {
        return;
      }

      if (startBlock !== endBlock && !startBlock.isBefore(endBlock)) return;
      if (startBlock === endBlock && selection.startOffset > selection.endOffset) return;

      const startPoint = getBlockPoint(startBlock, selection.startOffset, 'start');
      const endPoint = getBlockPoint(endBlock, selection.endOffset, 'end');
      if (!startPoint || !endPoint) return;
      if (
        !isValidLexicalPoint(startPoint.key, startPoint.offset, startPoint.type) ||
        !isValidLexicalPoint(endPoint.key, endPoint.offset, endPoint.type)
      ) {
        return;
      }

      const range = $createRangeSelection();
      setRangePoint(range, startPoint, 'anchor');
      setRangePoint(range, endPoint, 'focus');
      let quotedText: string;
      try {
        quotedText = range.getTextContent();
      } catch {
        return;
      }
      if (
        normalizeRewriteText(quotedText) !== normalizeRewriteText(selection.quotedText) ||
        (selection.quotedTextHash !== undefined &&
          hashRewriteText(quotedText) !== selection.quotedTextHash)
      ) {
        return;
      }
      if (!quotedText) return;

      const targetNodeIds = validateTargetBlocks(
        range,
        startBlock,
        endBlock,
        selection.targetNodeIds,
      );
      if (!targetNodeIds) return;

      result = {
        baseStateVector: selection.baseStateVector,
        endNodeId: selection.endNodeId,
        endOffset: selection.endOffset,
        isBackward: false,
        quotedText: normalizeRewriteText(quotedText),
        selection: range,
        startNodeId: selection.startNodeId,
        startOffset: selection.startOffset,
        targetNodeIds,
        stateVectorDrifted: getStateVectorDrift(
          this.getStateVectorSafely(),
          selection.baseStateVector,
        ),
      };
    });

    return result;
  }
}

/**
 * Internal room-persistence/testing seam. This function is deliberately not
 * re-exported by `src/headless/index.ts`, so Agent workers receive no public
 * snapshot API. A persistence worker can be granted this seam when it owns
 * the room flush lifecycle.
 */
export async function __exportCollaborativeAgentEditorProjectionForPersistence(
  session: CollaborativeAgentEditor,
): Promise<CollaborativeAgentEditorProjection> {
  const state = internalStates.get(session);
  if (!state) throw new Error('CollaborativeAgentEditor is disconnected.');

  await moment();
  return {
    editorData: state.kernel.getDocument(
      'json',
    ) as unknown as SerializedEditorState<SerializedLexicalNode>,
    markdown: state.kernel.getDocument('markdown') as unknown as string,
  };
}

